class SecurityKnowledgeBase:
    def __init__(self):
        self.docs = KNOWLEDGE_BASE
        self.vectorizer = TfidfVectorizer(stop_words="english")
        self._doc_vectors = self.vectorizer.fit_transform([d["text"] for d in self.docs])

    def retrieve(self, query: str, top_k: int = 2) -> list:
        """
        Returns the top_k most relevant knowledge base entries for a query
        string (e.g. "high packet rate, many short flows, low payload").

        Returns
        -------
        list of dicts: [{"attack_type": ..., "text": ..., "similarity": float}, ...]
        """
        query_vec = self.vectorizer.transform([query])
        sims = cosine_similarity(query_vec, self._doc_vectors).flatten()
        top_idx = np.argsort(sims)[::-1][:top_k]
        return [
            {**self.docs[i], "similarity": round(float(sims[i]), 3)}
            for i in top_idx if sims[i] > 0
        ]

    def retrieve_by_attack_type(self, attack_type: str) -> dict:
        """Direct lookup when the attack_type label is already known (e.g. from
        Stage 1's multiclass label), skipping similarity search entirely."""
        for doc in self.docs:
            if doc["attack_type"].lower() == attack_type.lower():
                return doc
        return None
