"""
security_knowledge_base.py
============================
Stage 5 - Component 2: Grounding Context (LlamaIndex-lite)

The project plan calls for LlamaIndex to index security documentation
(CVE databases, attack references) so the LLM's explanations are grounded
in real definitions rather than improvised. LlamaIndex itself isn't
installed in this dev environment (no network access to pip install), so
this module implements the SAME retrieval concept — TF-IDF vector search
over a small curated knowledge base — using only sklearn, which IS
available. This is a legitimate, explainable substitute: the retrieval
mechanism (vectorize query, retrieve nearest documents) is architecturally
identical to what LlamaIndex does under the hood for simple corpora; you
lose LlamaIndex's chunking/re-ranking/multi-index conveniences, but the
core "retrieval-augmented" idea is the same.

On your team's machines with network access, swapping this for real
LlamaIndex + a real CVE feed (e.g. NVD's API) is a natural upgrade — the
`retrieve()` interface below is written so xai_pipeline.py wouldn't need
to change if you make that swap later.

The knowledge base entries below are written by us as concise, plain-
language descriptions of each attack category present in CIC-IDS2017 /
UNSW-NB15 — NOT verbatim copies of any external CVE text or article
(avoids any copyright/attribution concerns and keeps things self-contained
for a demo).
"""

